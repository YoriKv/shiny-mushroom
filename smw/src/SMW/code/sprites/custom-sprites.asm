; The rows naming each custom sprite's routines: one %SMW_CustomSprite
; line per normal sprite number and entry point -- Init, Main, or one of
; the five status entry points -- and one %SMW_CustomSpriteKind line per
; sprite of another kind, whose single entry point is its main. Naming a
; status routine or a kind is what plants its hook and its table.
;
; The editor regenerates this file from the project's own sprite files.
; It is shipped empty because there are none, so the feature with
; unedited tables runs exactly what the stock cartridge runs.
